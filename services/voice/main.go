func setupLogging() {
	lvl := slog.LevelInfo
	switch strings.ToLower(os.Getenv("LOG_LEVEL")) {
	case "debug":
		lvl = slog.LevelDebug
	case "warn":
		lvl = slog.LevelWarn
	case "error":
		lvl = slog.LevelError
	}
	h := slog.NewTextHandler(os.Stdout, &slog.HandlerOptions{Level: lvl})
	slog.SetDefault(slog.New(h))
}

func main() {
	// Load .env before logging is configured so LOG_LEVEL (and everything else)
	// from the file is visible to setupLogging(); loadConfig() calls Load() again,
	// which is a no-op for already-set vars.
	_ = godotenv.Load()
	setupLogging()

	dryRun := flag.Bool("dry-run", false, "Read the leads CSV and print who would be dialled, without calling anyone")
	local := flag.Bool("local", false, "Local VOICE mode — talk to the agent via your laptop mic/speaker (needs ffmpeg), no Telnyx call")
	probe := flag.Bool("probe", false, "SCRIPT probe — type the prospect's lines; prints verbatim what the agent says and every tool call (no phone, no mic)")
	mic := flag.String("mic", "", "Microphone device name for -local (dshow). Default: auto-detect")
	simProspect := flag.String("sim-prospect", "", "Which lead to rehearse against: \"\" (first), \"#42\" (by row), \"miller\" (by name), or \"Name|City|Rating|Reviews\" (manual stub)")
	bench := flag.Bool("bench", false, "Measure reply latency against the real live session using a recorded prospect turn — no phone call")
	benchTrials := flag.Int("bench-trials", 5, "How many measured sessions per setting in -bench")
	benchTurns := flag.Int("bench-turns", 2, "Measured turns per session in -bench; turn 1 is the one the prospect judges")
	benchUtterance := flag.String("bench-utterance", "bench/utt_medium.pcm8k", "Raw PCM16 mono 8kHz of a real prospect turn, for -bench")
	benchSilence := flag.String("bench-silence", "", "Comma-separated silenceDurationMs values to sweep in -bench, e.g. 100,200,300")
	ttsBench := flag.Bool("tts-bench", false, "Time ElevenLabs synthesis from this machine — one-shot and streaming time-to-first-chunk")
	runTag := flag.String("run", "", "Name this run. Events go to campaignlogs/<run>.jsonl and the end-of-run report is printed under it. Defaults to a timestamp.")
	report := flag.String("report", "", "Read a run's event file back as a funnel and a set of distributions, then exit — e.g. -report campaignlogs/live2.jsonl")
	say := flag.String("say", "", "Synthesise these lines (separated by \"|\") through the live voice and report how long each takes to say — for tuning wording")
	openerPreview := flag.Int("opener-preview", 0, "Synthesise the opening line for the first N leads, print how long each takes to say, and write them as .wav — no phone call")
	openerPreviewDir := flag.String("opener-preview-dir", "opener_preview", "Where -opener-preview writes its .wav files (\"\" = don't write any)")
	maxAnswered := flag.Int("max-answered", 0, "Stop the campaign after this many calls are ANSWERED (0 = run the whole list). Bounds a test run to a handful of real people.")
	allowUndelivered := flag.Bool("allow-undelivered", false, "Run even though Google Calendar is not connected. Every meeting agreed on a call becomes a promise that is never kept — for pipeline testing only")
	flag.Parse()

	// -report reads a finished run back. No config, no network, no calls.
	if *report != "" {
		runReportMode(*report)
		return
	}

	cfg := loadConfig()

	// -bench / -tts-bench: measurement modes. No phone, no Telnyx — just the real
	// model over the real audio path, so latency work needs no live victims.
	if *bench || *ttsBench {
		if cfg.OpenAIAPIKey == "" {
			slog.Error("-bench/-tts-bench needs OPENAI_API_KEY and ELEVENLABS_API_KEY")
			os.Exit(1)
		}
		if *ttsBench {
			runTTSBench(cfg, *benchTrials)
		}
		if *bench {
			runBench(cfg, benchOpts{
				trials:    *benchTrials,
				turns:     *benchTurns,
				utterance: *benchUtterance,
				silences:  parseBenchSilences(*benchSilence),
			})
		}
		return
	}

	if *say != "" {
		if cfg.ElevenAPIKey == "" {
			slog.Error("-say needs ELEVENLABS_API_KEY")
			os.Exit(1)
		}
		runSayPreview(cfg, strings.Split(*say, "|"), *openerPreviewDir)
		return
	}

	// -opener-preview: synthesis only. No Telnyx, no call, no prospect.
	if *openerPreview > 0 {
		if cfg.ElevenAPIKey == "" {
			slog.Error("-opener-preview needs ELEVENLABS_API_KEY")
			os.Exit(1)
		}
		runOpenerPreview(cfg, *openerPreview, *openerPreviewDir)
		return
	}

	// -local / -probe: offline test modes. No Telnyx, no phone, no stranger.
	if *local || *probe {
		if cfg.OpenAIAPIKey == "" {
			slog.Error("-local/-probe needs OPENAI_API_KEY (and ELEVENLABS_API_KEY for -local)")
			os.Exit(1)
		}
		switch {
		case *local:
			runLocal(cfg, *simProspect, *mic)
		default:
			runProbe(cfg, *simProspect)
		}
		return
	}

	// Required config
	missing := []string{}
	if cfg.TelnyxAPIKey == "" {
		missing = append(missing, "TELNYX_API_KEY")
	}
	if cfg.TelnyxConnectionID == "" {
		missing = append(missing, "TELNYX_CONNECTION_ID")
	}
	if cfg.FromNumber == "" {
		missing = append(missing, "FROM_NUMBER")
	}
	if cfg.OpenAIAPIKey == "" {
		missing = append(missing, "OPENAI_API_KEY")
	}
	if cfg.ElevenAPIKey == "" {
		missing = append(missing, "ELEVENLABS_API_KEY")
	}
	if cfg.ElevenVoiceID == "" {
		missing = append(missing, "ELEVENLABS_VOICE_ID")
	}
	if cfg.PublicHost == "" {
		missing = append(missing, "PUBLIC_HOST")
	}
	if len(missing) > 0 {
		slog.Error("missing required env vars", "vars", missing)
		os.Exit(1)
	}

	prospects, err := ReadProspects(cfg.ProspectsFile)
	if err != nil {
		slog.Error("read prospects", "file", cfg.ProspectsFile, "error", err)
		os.Exit(1)
	}
	slog.Info("loaded prospects", "count", len(prospects), "file", cfg.ProspectsFile)

	if *dryRun {
		// One clock covers this whole list — India is a single timezone — so a dry
		// run is just the list. run_campaign.sh owns the calling window.
		for _, p := range prospects {
			slog.Info("would dial", "dial", p.DialNumber(), "direct", p.DirectNumber != "",
				"main", p.Phone, "owner", p.OwnerName, "business", p.Name, "city", p.City)
		}
		slog.Info("dry run complete", "would_dial", len(prospects))
		return
	}

	sessions := NewSessionRegistry(cfg)

	mux := http.NewServeMux()
	mux.HandleFunc("/webhook", HandleWebhook(cfg, sessions))
	mux.Handle("/media-stream", HandleMediaStream(cfg, sessions))
	mux.HandleFunc("/health", func(w http.ResponseWriter, r *http.Request) {
		w.Write([]byte("ok"))
	})

	srv := &http.Server{
		Addr:    ":" + cfg.Port,
		Handler: mux,
	}

	// Run webhook server in the background
	srvDone := make(chan error, 1)
	go func() {
		slog.Info("webhook server starting", "addr", srv.Addr, "public", cfg.PublicHost)
		err := srv.ListenAndServe()
		if !errors.Is(err, http.ErrServerClosed) {
			srvDone <- err
		}
	}()

	// Catch Ctrl+C
	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()

	// Give the server a moment to come up.
	time.Sleep(500 * time.Millisecond)

	// Google Calendar owns the entire follow-up: book_meeting is the win, and the
	// invite with the Meet link is what makes it real. If Calendar isn't connected,
	// every "yeah, Thursday works" on the call is a promise that silently never
	// lands — the exact failure the India build's WhatsApp guard existed to stop,
	// where seven live calls went out against an unlinked sidecar and each one told
	// a real person their link was on the way.
	//
	// So this refuses to dial rather than warning. A warning is something you walk
	// past. -allow-undelivered is the deliberate override for pipeline testing, and
	// it has to be typed.
	if ready, detail := WhatsAppReady(cfg); ready {
		slog.Info("whatsapp sidecar ready", "api", cfg.WhatsAppAPI, "detail", detail)
	} else if *allowUndelivered {
		slog.Warn("WHATSAPP SIDECAR NOT READY — running anyway (-allow-undelivered). Demo links will NOT be delivered",
			"api", cfg.WhatsAppAPI, "reason", detail)
	} else {
		slog.Error("REFUSING TO DIAL — WhatsApp is not linked, so every demo link promised on a call would silently never arrive",
			"api", cfg.WhatsAppAPI, "reason", detail,
			"fix", "link the sidecar (see whatsapp/README.md), or pass -allow-undelivered to test the call pipeline without delivery")
		os.Exit(1)
	}

	// Openers are synthesised ahead of the dial (see openai.go). Warm the generic
	// fallback now so the very first call doesn't pay for it, and prime the
	// lookahead window before the loop starts.
	openers := NewOpenerCache(cfg)
	{
		genCtx, genCancel := context.WithTimeout(ctx, 40*time.Second)
		// Order matters, and it is not the obvious one. The generic opener is the
		// greeting every call falls back to when a personalised one isn't ready, so
		// it is synthesised FIRST and alone: run concurrently with the filler pool,
		// it lost the race for Gemini's per-minute quota and calls would have opened
		// in silence while "हम्म..." sat ready in memory.
		openers.Generic(genCtx)
		WarmThinkingFillers(genCtx, cfg)
		genCancel()
		for i := 0; i < cfg.OpenerLookahead && i < len(prospects); i++ {
			openers.Prefetch(ctx, prospects[i])
		}
		// Every lead from the second onward has its opener synthesised during the
		// previous call, so it is always ready in time. The first one has no
		// previous call to hide behind — so wait for it here, before dialling,
		// rather than letting lead #1 fall back to the generic greeting.
		if len(prospects) > 0 {
			openers.Get(ctx, prospects[0], 30*time.Second)
		}
	}

	// The run log. Every call writes one JSON object into it as it finishes, and
	// the manifest at the top records the exact tuning they all ran under — the
	// first live campaign had to be reconstructed from a text log, a CSV whose
	// disposition column was wrong, and six recordings measured by hand.
	tag := *runTag
	if tag == "" {
		tag = "run_" + time.Now().Format("20060102_150405")
	}
	if err := os.MkdirAll("campaignlogs", 0o755); err != nil {
		slog.Warn("could not create campaignlogs/ — this run will not be replayable", "error", err)
	}
	eventsPath := filepath.Join("campaignlogs", tag+".jsonl")
	if rl, err := OpenRunLog(eventsPath, tag); err != nil {
		slog.Warn("could not open the run log — the campaign will run, but nothing will be replayable afterwards",
			"path", eventsPath, "error", err)
	} else {
		runLog = rl
		defer runLog.Close()
		slog.Info("run log open", "run", tag, "events", eventsPath,
			"read_it_back_with", "./voice-agent -report "+eventsPath)
	}

	// "call मत करो" is an instruction, not an outcome. Loaded before the first
	// dial and appended the moment somebody asks, so a run killed mid-campaign
	// does not lose the fact that they did.
	suppression := LoadSuppression(cfg.SuppressionFile)

	waReady, waDetail := WhatsAppReady(cfg)
	runLog.Manifest(cfg, len(prospects), *maxAnswered, map[string]any{
		"whatsapp_linked": waReady,
		"whatsapp_detail": waDetail,
	})

	// The sidecar's own counters, sampled into the same file as the calls. This
	// account is the fragile part of the whole system — an unofficial client
	// messaging strangers from a real personal number — so sampling it here is
	// what makes "the unreachable count rose during this run" a thing you can see
	// rather than a thing you would have to already suspect.
	waHealth := whatsAppWatch(cfg, "start", nil)

	// health watches whether the agent is actually conversing, not just dialling.
	// A silently broken agent produces calls that look like ordinary hangups, and
	// the run would otherwise work through the whole list that way.
	var health campaignHealth

	// answered counts calls a human actually picked up. A test run is bounded on
	// THIS rather than on dials, because dials are mostly rings-out and a limit of
	// "20 numbers" can mean anything between zero and twenty real conversations.
	answered := 0

	// deadDials counts consecutive dials that never carried a frame of audio, and
	// deadCauses remembers what the carrier said about them — see routeFailLimit.
	deadDials := 0
	var deadCauses []string

	// skipped counts leads the compliance gate refused. Reported at the end,

	// Run the campaign sequentially.
campaign:
	for i, p := range prospects {
		if *maxAnswered > 0 && answered >= *maxAnswered {
			slog.Info("stopping: reached the answered-call limit for this run",
				"answered", answered, "limit", *maxAnswered, "dialled", i)
			break campaign
		}

		select {
		case <-ctx.Done():
			slog.Info("interrupted")
			break campaign
		default:
		}

		// Circuit breaker: if the brain couldn't connect (on either key) for the
		// last few calls in a row, the API is effectively down — stop cold calling
		// rather than burn through the rest of the list with dead calls.
		if brainConsecutiveFails.Load() >= brainFailLimit {
			slog.Error("stopping campaign: the Realtime API failed on consecutive calls (both keys)",
				"consecutive_fails", brainConsecutiveFails.Load(), "limit", brainFailLimit)
			break campaign
		}

		// Route circuit breaker. Six dials in a row that never carried a frame of
		// audio is not a run of busy people, it is the path to India being down —
		// and every further dial spends a lead to learn nothing.
		if deadDials >= routeFailLimit {
			slog.Error("STOPPING CAMPAIGN — the last dials in a row never connected at all",
				"consecutive_dead_dials", deadDials, "limit", routeFailLimit,
				"last_causes", strings.Join(deadCauses, ", "),
				"meaning", "no answer signal and no media from the carrier. Either nobody on this list is picking up, or the route from "+cfg.FromNumber+" has stopped completing calls — which on a US-to-India route usually means the carrier has stopped completing them.",
				"check", "dial one number by hand (./testcall.sh +919XXXXXXXXX) and see whether it connects before spending more leads")
			break campaign
		}

		// Keep the synthesis pipeline `OpenerLookahead` leads ahead of the dial, so
		// each lead's personalised opening line is already sitting in memory by the
		// time we call them. This work happens entirely inside the previous call.
		for j := i; j < i+cfg.OpenerLookahead+1 && j < len(prospects); j++ {
			openers.Prefetch(ctx, prospects[j])
		}

		dialNum := p.DialNumber() // owner/direct line when we have one, else main line
		log := slog.With("phone", dialNum, "business", p.Name, "i", i+1, "n", len(prospects))

		log.Info("dialing", "direct", dialNum != p.Phone)
		callControlID, err := telnyxDial(cfg, dialNum)
		if err != nil {
			log.Error("dial failed", "error", err)
			_ = AppendResult(cfg.ResultsFile, Result{
				Phone:       dialNum,
				Business:    p.Name,
				City:        p.City,
				Rating:      p.Rating,
				Reviews:     p.TotalReviews,
				Disposition: "dial_failed",
				HangupBy:    "dial_failed",
				Timestamp:   time.Now(),
			})
			continue
		}

		sess := sessions.Create(callControlID, p)
		sess.Phone = dialNum // log/record the number we actually dialed
		sess.seq = i + 1

		// Hand over this lead's opening audio. Prefetch normally finished during the
		// previous call, so this returns immediately; the short wait only matters for
		// the very first lead, and on timeout we fall back to the generic greeting.
		sess.fillerMulaw, sess.openerPersonal = openers.Get(ctx, p, 2*time.Second)

		// Record the line that will ACTUALLY be spoken, which is not always this
		// lead's personalised one — synthesis can fail or arrive late and the
		// generic greeting stands in. The event record has to say which, or a run
		// where the opener quietly degraded reads as one where it did not.
		sess.openerLine = fillerLine()
		if sess.openerPersonal {
			sess.openerLine = openerLine(p)
		}

		// Pre-connect the brain WHILE THE PHONE IS STILL RINGING. Opening the WebSocket
		// and completing setup takes a few hundred milliseconds; doing it after
		// pickup puts that squarely in the silence the prospect is judging us on.
		// Ringing gives us 10-30 seconds of otherwise-wasted time to spend on it.
		// If it fails, HandleMediaStream just connects normally on answer.
		go func(s *Session, p Prospect, personal bool) {
			g, err := ConnectBrain(s.ctx, cfg,
				buildCallInstruction(cfg, p, len(s.fillerMulaw) > 0, personal))
			if err != nil {
				if s.ctx.Err() == nil {
					slog.Debug("gemini pre-connect failed; will connect on answer", "error", err)
				}
				return
			}
			// The media stream may have attached and connected in the meantime.
			if !s.installBrain(g) {
				g.Close()
			}
		}(sess, p, sess.openerPersonal)

		// The voice socket is pre-connected for exactly the same reason: a TLS
		// handshake is 100-200ms and belongs in the ringing, not in the pause after
		// somebody says hello.
		go func(s *Session) {
			v, err := ConnectVoice(s.ctx, cfg)
			if err != nil {
				if s.ctx.Err() == nil {
					slog.Debug("voice pre-connect failed; will connect on answer", "error", err)
				}
				return
			}
			if !s.installVoice(v) {
				v.Close()
			}
		}(sess)

		// Wait for the call to complete (or timeout).
		var result Result
		select {
		case result = <-sess.Done():
			// got it
		case <-time.After(cfg.CallTimeout):
			log.Warn("call timeout", "timeout", cfg.CallTimeout)
			_ = telnyxHangup(cfg, callControlID)
			sess.Finish("timeout")
			result = <-sess.Done()
		case <-ctx.Done():
			_ = telnyxHangup(cfg, callControlID)
			sess.Finish("interrupted")
			result = <-sess.Done()
		}

		if result.HangupBy != "dial_failed" && result.Disposition != "no_answer" && result.Disposition != "voicemail" {
			answered++
		}

		// Track how many dials in a row produced no call at all, and what the
		// carrier said about them. One is normal; six in a row is a broken route.
		if deadDial(result) {
			deadDials++
			cause := sess.hangupCauseString()
			if cause == "" {
				cause = result.Disposition
			}
			deadCauses = append(deadCauses, cause)
			if len(deadCauses) > routeFailLimit {
				deadCauses = deadCauses[1:]
			}
		} else {
			deadDials, deadCauses = 0, nil
		}

		// "Take me off your list" is an instruction, not an outcome. It has to
		// outlive this call, and it has to be written the moment it is known — a
		// campaign killed mid-run must not lose the fact that somebody asked.
		if sess.doNotCall.Load() || result.Disposition == "do_not_call" {
			suppression.Add(dialNum, "asked to be removed on call "+result.CallID)
		}

		sessions.Remove(callControlID)
		openers.Forget(p) // a long run must not hold every opener it ever made

		if err := AppendResult(cfg.ResultsFile, result); err != nil {
			log.Error("append result", "error", err)
		}

		// Is the agent still holding conversations? Checked every
		// healthCheckEvery dials, on the calls that actually gave it a chance.
		health.record(result)
		if health.due() {
			if stop, reason := health.check(slog.Default()); stop {
				slog.Error("STOPPING THE CAMPAIGN — something is wrong with the agent itself, not the leads",
					"reason", reason, "dialled", health.dials,
					"next", "check the last few calls in the run log: "+cfg.ResultsFile+
						" and campaignlogs/, and listen to a recording before dialling anyone else")
				break campaign
			}
		}
		log.Info("call complete",
			"answered_so_far", answered, "limit", *maxAnswered,
			"owner", result.OwnerName, "disposition", result.Disposition,
			"link", result.LinkChannel, "link_status", result.LinkStatus,
			"lang", result.Language, "callback", result.Callback, "hangup_by", result.HangupBy)

		// Small delay between calls so we don't hammer carriers.
		if i < len(prospects)-1 {
			time.Sleep(cfg.DelayBetween)
		}
	}

	// Keep the webhook server alive briefly so Telnyx's post-call webhooks —
	// especially call.recording.saved, which arrives a few seconds after hangup —
	// can be received and the recording downloaded. Without this the server would
	// shut down immediately and those webhooks would 502.
	if cfg.RecordEnabled && cfg.RecordingGrace > 0 {
		slog.Info("waiting for recordings to finalize", "grace", cfg.RecordingGrace)
		select {
		case <-time.After(cfg.RecordingGrace):
		case <-ctx.Done():
		}
	}

	// The last thing the run does is read itself back. "How did that go?" should
	// be answered on the screen the operator is already looking at, not in a file
	// they have to know exists.
	whatsAppWatch(cfg, "end", &waHealth)
	if summary := runLog.Summarise(); summary != "" {
		fmt.Println(summary)
		fmt.Printf("\n   full detail, every call and every transcript:\n   ./voice-agent -report %s\n\n", eventsPath)
	}

	slog.Info("campaign finished — shutting down")
	shutdownCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	_ = srv.Shutdown(shutdownCtx)

	select {
	case err := <-srvDone:
		if err != nil {
			slog.Warn("server exited with error", "error", err)
		}
	default:
	}
}
